validate_signature <- function(data, label) {
  if (!("analysis_signature" %in% names(data))) {
    stop(label, " lacks analysis_signature.", call. = FALSE)
  }

  signatures <- unique(as.character(data$analysis_signature))
  signatures <- signatures[!is.na(signatures) & nzchar(signatures)]

  if (length(signatures) != 1L || signatures[1] != ANALYSIS_SIGNATURE) {
    stop(
      label,
      " was not generated by the current code. Run 07_run_all.R.",
      call. = FALSE
    )
  }
}

